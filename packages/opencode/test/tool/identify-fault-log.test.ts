// （resources/skills/hmos-dfx-analyzer/scripts/identify_fault_log.py）。
// 本测试通过子进程执行该脚本，钉板其结构化输出与决策表的一致性。
// 运行依赖 python3；不可用时整组跳用（脚本契约由 hmos-dfx-analyzer skill 测试另行守护）。

const SCRIPT = path.resolve(import.meta.dir, "../../resources/skills/hmos-dfx-analyzer/scripts/identify_fault_log.py")

function pythonAvailable(): boolean {
  const probe = spawnSync("python3", ["--version"], { encoding: "utf-8" })
  return probe.status === 0
}

const hasPython = pythonAvailable()

interface ClassifyResult {
  type: string
  subtype?: string
  confidence: string
  completeness: string
  evidence: string[]
  excluded: { type: string; reason: string }[]
  candidates: { type: string; confidence: string; evidence: string[] }[]
  memory_corruption_suspect?: { suspected: boolean; confidence: string; evidence: string[] }
  out_of_scope?: { reason: string; detail: string }
}

function classify(sample: string): ClassifyResult {
  const proc = spawnSync("python3", [SCRIPT, "--stdin"], {
    input: sample,
    encoding: "utf-8",
  })
  if (proc.status !== 0) throw new Error(`identify_fault_log.py failed: ${proc.stderr}`)
  return JSON.parse(proc.stdout)
}

// Task 9: 决策表与判别器取值的一致性检查。
// 摸清识别脚本实际可能产出的字段取值组合，与主 Skill
// （resources/skills/hmos-dfx-analyzer/SKILL.md 的「结果处置决策表」）覆盖的分支一一对应。
// 捕获两类问题：未覆盖（脚本新增取值无对应格）与死格（决策表存在脚本永不产出的组合）。

type TypeBucket = "明确类型" | "unknown"
type CandState = "empty" | "nonempty"

interface Signature {
  type: TypeBucket
  candidates: CandState
  outOfScope: boolean
  concreteType: string
}

function signatureOf(result: ClassifyResult): Signature {
  return {
    type: result.type === "unknown" ? "unknown" : "明确类型",
    candidates: result.candidates.length > 0 ? "nonempty" : "empty",
    outOfScope: Boolean(result.out_of_scope),
    concreteType: result.type,
  }
}

